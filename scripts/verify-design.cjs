const fs=require('node:fs');
const path=require('node:path');
const {spawn}=require('node:child_process');
const {pathToFileURL}=require('node:url');
const root=process.cwd(), folder=path.join(root,'design/final-2026-10-12');
const output=path.join(root,'artifacts/final-design-browser');
fs.mkdirSync(output,{recursive:true});
const profile=path.join(output,'profile-'+Date.now());
const downloads=path.join(profile,'downloads');fs.mkdirSync(downloads,{recursive:true});
const chrome='C:/Program Files/Google/Chrome/Application/chrome.exe';
const browser=spawn(chrome,['--headless=new','--disable-gpu','--no-first-run','--no-default-browser-check','--disable-background-networking','--disable-extensions','--disable-sync','--disable-component-update','--remote-debugging-port=0','--user-data-dir='+profile,'about:blank'],{windowsHide:true,stdio:'ignore'});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
let socket;
const watchdog=setTimeout(()=>{console.error('Browser verification timeout');socket?.close();browser.kill();process.exit(1);},25000);
(async()=>{
 let active;
 for(let n=0;n<100;n++){try{active=fs.readFileSync(path.join(profile,'DevToolsActivePort'),'utf8');break;}catch{}await sleep(100);}
 if(!active)throw Error('Headless browser did not start');
 const port=active.split('\n')[0];
 console.log('Headless browser started');
 const targets=await(await fetch('http://127.0.0.1:'+port+'/json/list')).json();
 socket=new WebSocket(targets.find(t=>t.type==='page').webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{socket.addEventListener('open',resolve,{once:true});socket.addEventListener('error',reject,{once:true});});
 let next=0;const pending=new Map();const errors=[];
 socket.addEventListener('message',e=>{const m=JSON.parse(e.data);if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails.text);if(m.id){const p=pending.get(m.id);pending.delete(m.id);if(m.error)p.reject(Error(JSON.stringify(m.error)));else p.resolve(m.result);}});
 socket.addEventListener('close',()=>{for(const p of pending.values())p.reject(Error('Browser connection closed'));pending.clear();});
 const send=(method,params={})=>new Promise((resolve,reject)=>{const id=++next;pending.set(id,{resolve,reject});socket.send(JSON.stringify({id,method,params}));});
 const evaluate=async expression=>{const r=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
 const check=(value,name)=>{if(!value)throw Error(name);console.log('PASS '+name);};
 await send('Page.enable');await send('Runtime.enable');
 await send('Emulation.setDeviceMetricsOverride',{width:1600,height:1150,deviceScaleFactor:1,mobile:false});
 await send('Page.navigate',{url:pathToFileURL(path.join(folder,'index.html')).href});
 for(let n=0;n<100;n++){if(await evaluate("document.querySelectorAll('#navigation button').length===15"))break;await sleep(100);}
 check(await evaluate("document.querySelectorAll('#navigation button').length===15"),'15 design boards available');
 check(await evaluate("Promise.all([...document.images].map(async im=>{im.loading='eager';try{await im.decode();return im.naturalWidth>0;}catch{return false;}})).then(r=>r.every(Boolean))"),'Every gallery image decodes');
 await evaluate("document.querySelectorAll('#navigation button')[8].click()");
 check(await evaluate("document.querySelector('#title').textContent==='디스크' && document.querySelector('#preview').getAttribute('src')==='08-disk.png'"),'Disk final composition navigation');
 await evaluate("document.querySelector('#notes').value='검수 저장 확인';document.querySelector('#notes').dispatchEvent(new Event('input'));document.querySelector('#status').value='change';document.querySelector('#status').dispatchEvent(new Event('change'))");
 await send('Page.reload');await sleep(450);
 check(await evaluate("document.querySelector('#notes').value==='검수 저장 확인' && document.querySelector('#status').value==='change'"),'Review notes and state persist after reload');
 await send('Browser.setDownloadBehavior',{behavior:'allow',downloadPath:downloads});
 await evaluate("document.querySelector('#export').click()");
 let exported;
 for(let n=0;n<50;n++){exported=fs.readdirSync(downloads).find(x=>/^tempos-design-review-.*\.json$/.test(x));if(exported)break;await sleep(100);}
 check(!!exported,'Review JSON export created');
 const payload=JSON.parse(fs.readFileSync(path.join(downloads,exported),'utf8'));
 check(payload.reviews.length===15 && payload.reviews.find(x=>x.id==='disk').notes==='검수 저장 확인','Export includes all boards and the review note');
 await evaluate("document.querySelector('#notes').value='';document.querySelector('#notes').dispatchEvent(new Event('input'));document.querySelector('#status').value='unreviewed';document.querySelector('#status').dispatchEvent(new Event('change'));document.querySelectorAll('#navigation button')[2].click()");
 await evaluate("document.querySelector('#preview').decode()");
 await sleep(150);
 let shot=await send('Page.captureScreenshot',{format:'png'});fs.writeFileSync(path.join(output,'desktop.png'),Buffer.from(shot.data,'base64'));
 check(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Desktop gallery fits viewport');
 await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await sleep(150);
 check(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Mobile gallery fits viewport');
 shot=await send('Page.captureScreenshot',{format:'png'});fs.writeFileSync(path.join(output,'mobile.png'),Buffer.from(shot.data,'base64'));
 await send('Page.navigate',{url:pathToFileURL(path.join(folder,'app-review.html')).href});
 await sleep(150);
 check(await evaluate("document.querySelectorAll('section[id^=kind-]').length===9"),'Nine actual-app review sections');
 check(await evaluate("Promise.all([...document.images].map(async im=>{im.loading='eager';try{await im.decode();return im.naturalWidth>0;}catch{return false;}})).then(r=>r.length>=120&&r.every(Boolean))"),'Actual app capture and reference images decode');
 check(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Mobile app review fits viewport');
 await send('Emulation.setDeviceMetricsOverride',{width:1600,height:1150,deviceScaleFactor:1,mobile:false});
 await sleep(100);
 shot=await send('Page.captureScreenshot',{format:'png'});fs.writeFileSync(path.join(output,'app-desktop.png'),Buffer.from(shot.data,'base64'));
 check(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Desktop app review fits viewport');
 check(errors.length===0,'No browser script errors');
 await send('Browser.close').catch(()=>{});
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>{clearTimeout(watchdog);socket?.close();browser.kill();});
